(* ::Input::Initialization:: *)
portVolbyVCVextended[seclist_,holdings_,settledate_]:=Module[{x,y,portDV01s,portvcv,portvol,rflist,mcp,mcl,cov,contallornot,besthedge,volbesthedge,volsbyrf,portDV01s1,intermedvec,corr,repport,xx1,i,j,indexes},
portDV01s=populatePortDV01s[seclist,holdings,settledate];
xx1=populateEqvDV01s[seclist,settledate];
  (* This is the RF DV01s for unit holdings of everything. Used later to get Best Hedge amounts in units of mn holdings *)
indexes = Table[Position[portDV01s[[1]],xx1[[1]][[i]]],{i,1,Length[xx1[[2]]]}];
indexes = Flatten[indexes];          (* This creates list of indexes of elements with eqv DV01s into the full list of all portfolio DV01s *)
portDV01s1 = portDV01s;
portDV01s1[[2]] = 0*portDV01s[[2]];  (* This creates a holder with the right names and zeros for DV01s *)
portDV01s1[[2]][[indexes]] = xx1[[2]];  (* Now this populates the values of the DV01s in the right order *)
rflist = portDV01s[[1]];
portvcv=populateVCV[rflist];
cov = portvcv . portDV01s[[2]]; (* Intermediate result - essentially covariance - used for both port vol and Marg Cont'n  - in text called Subscript[x [\[CapitalSigma]\[Omega]], k] *)
x=portDV01s[[2]] . cov; (* This is the portfolio variance *)
portvol = Sqrt[x]; (* Get vol rather than variance *)
intermedvec=portDV01s[[2]] * cov; (* Intermediate vector, used in calculation of marginal and all-or-nothing contribution. Note that this is element-by-element multiplication, not dot product. In the text, Subscript[\!\(
\(\*SubsuperscriptBox[\(\[Omega]\), \(i\), \('\)]\)[\[CapitalSigma]\[Omega]]\), k]   *)
mcl = intermedvec / portvol; (* This is Marginal Contribution in levels *)
mcp = mcl / portvol; (* Divide through by another factor of vol to get MC proportional *)
y = Diagonal[portvcv]; (* Diagonal elements - sigxx - used in a few places *)
corr = cov / (portvol*Sqrt[y]);  (* Correlation of RFs with portfolio *)
volsbyrf = portDV01s[[2]]*portDV01s[[2]]*y;
contallornot = portvol - Sqrt[x - 2*intermedvec + volsbyrf];
  (* All-or-nothing contribution to volatility - change in vol when this pos'n set to zero *)
besthedge = Table[If[portDV01s1[[2,i]] != 0,(portDV01s[[2,i]] - cov[[i]] / y[[i]]) / portDV01s1[[2,i]],0],{i,1,Length[portDV01s[[2]]]}]; (* This produces besthedges as proportion of input holding *)
repport = Table[If[portDV01s1[[2,i]] != 0,(cov[[i]] / y[[i]]) / portDV01s1[[2,i]],0],{i,1,Length[portDV01s[[2]]]}];  (* Replicating portfolio as proportion of input holding *)
(*besthedge = besthedge * holdings;*) (* This is now in millions (as in holdings) *)
volbesthedge = Sqrt[x-(cov*cov)/y]; (* Volatility at best hedge position *)
Return[{portvol,mcl,mcp,contallornot,besthedge,volbesthedge,Sqrt[volsbyrf],rflist,portDV01s1[[2]],corr,repport,portDV01s[[2]],portvcv}]
]



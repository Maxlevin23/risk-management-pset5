(* ::Input::Initialization:: *)
bondprc[yld_,settledate_,parms_] := Module[{yldperiod,nper,pmt,d0,d1,d2,d3,d4,d0sd,d1sd,d2sd,d3sd,d4sd,matsd,settlesd,dbefore,dafter,bondpv,dayfrac,ai,prc,hlfyr,floatreset},
yldperiod = yld/parms[[3]];
If[parms[[3]]==1,hlfyr=12,hlfyr=6];  (* This makes it work for both ann and semi-ann, for checking dates before and after *)
matsd = serialday[parms[[2]]];
d2 = parms[[2]];d2[[1]]=settledate[[1]];   (* Insert today's year into maturity date *)
(* Create dates before and after *) 
d0 = DatePlus[d2,{-12,"Month"}];d1 = DatePlus[d2,{-hlfyr,"Month"}]; 
d3 = DatePlus[d2,{hlfyr,"Month"}];d4 = DatePlus[d2,{12,"Month"}];  
d0sd = serialday[d0];d1sd = serialday[d1];d2sd = serialday[d2];
d3sd = serialday[d3];d4sd = serialday[d4];
settlesd=serialday[settledate];
Which[d0sd<settlesd<=d1sd,dbefore=d0sd;dafter=d1sd;, (* This figures out the prior and next coupon dates *)
d1sd<settlesd<=d2sd,dbefore=d1sd;dafter=d2sd;,
d2sd<settlesd<=d3sd,dbefore=d2sd;dafter=d3sd;,
d3sd<settlesd<=d4sd,dbefore=d3sd;dafter=d4sd;];
dayfrac = (dafter-settlesd)/(dafter-dbefore);
nper = Round[(matsd - dafter)/(365/parms[[3]])];
pmt = parms[[1]]/parms[[3]];
bondpv=pv[yldperiod,nper,pmt,100];     (* PV of payments after fractional period *)
bondpv = (pmt + bondpv)/((1+yldperiod)^dayfrac);  (* Next payment and discount *)
If[Length[parms] == 5, (* Swap has 5 parms. Not a robust way to distinguish bond from swap *)
floatreset=parms[[4]]/parms[[3]];  (* Next float reset. Assume A/A and same frequency as fixed. Not really correct
for a real USD swap, where float is A/365 and usually quarterly *)
bondpv = bondpv - (floatreset+100)/((1+yldperiod)^dayfrac);,
Null];     (* Not a robust check, but if 5 then this is a swap (has "FloatReset") *)
ai =  pmt*(1-dayfrac);
prc = bondpv - ai;
{prc,ai,bondpv}    (* Return a list including clean price, AI, and dirty price *)
]



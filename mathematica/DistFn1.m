serialday[date_] := IntegerPart[FromDate[date]/86400] + 2


(* ::Input::Initialization:: *)
dateday[serialday_] := ToDate[86400*(serialday - 2)]


(* ::Input::Initialization:: *)
pv[rate_,nper_,pmt_,fv_] := pmt*(1 - (1/((1+rate)^nper)))/rate + fv/((1+rate)^nper)



calcSimulatedPL[seclist_, holdings_, settledate_, inputRFs_] := Module[{xup,  bumpunit, countsec, countrf,  parms, rflist, i, j, k, isec, irf, irfsec, in, leveltst, inup, h, mktinplist, xmarketDataup,  icrv, x2, crvname, xcurve, xcurveup, ix, mktinputsup, irfmkt, ndraws, inputRFlist, portrevals, baseval, pandl},
      rflist = inputRFs[[1]];  (* List of RFs in the simulation *)
      countrf = Length[rflist];
      countsec = Length[seclist];
      ndraws = Length[inputRFs] - 1;   (* Number of draws - first row is list of RF names *)
      If[countrf*countsec == 0, Return["Error in calcSimulatedPL - seclist or rflist empty"], (* if OK then do the work of the function *)
       baseval = pvPort[seclist, holdings, settledate, marketDataValues];   (* Calculate base portfolio value *)
       pandl = ConstantArray[0, { ndraws + 1,countsec + 1}];                             (* Matrix to hold the P&L. Make it 1 longer than securities (last col holds total) and one longer than number of draws (first row holds seclist) *)
         pandl[[1, 1 ;; countsec]] = seclist;
         pandl[[1, countsec + 1]] = "Portfolio";
         For[k = 1, k <= ndraws, k++,                                                                  (* loop over simulation draws *)
              xmarketDataup = marketDataValues; (* populate the local version of market data - later the bumped RF values will be inserted *)
     For[i = 1, i <= countrf, i++,  (* loop over risk factors to populate new (bumped) market values *)
               (* First get the input and bump up / down *)
               irfmkt = Position[marketDataNames, rflist[[i]]][[1, 1]];
               in = marketDataValues[[irfmkt]];
irf = Position[riskFactorNames, rflist[[i]]][[1, 1]];
               h = inputRFs[[k+1,i]];
           leveltst = riskFactorBumpTypes[[irf]];
           bumpunit  = riskFactorBumpUnit[[irf]];
               Switch[leveltst,
             "level", inup = in + h;
                 (* Put up  into local market data *)
                 xmarketDataup[[irfmkt]] = inup; ,
             "percent", inup = in*(1 + h);  xmarketDataup[[irfmkt]] = inup; ,
             "levelcurveinp",(* This is a curve input variable *) (* SHOULD NOT WORK - need to change all curve inputs then re-build curve *)
             icrv = Position[seclist, rflist[[i]]][[1]];      (* In populateSecDV01s the variable secDV01Names was used. I think this should work but watch out *)
             x2 = secMktInputNames[[icrv[[1]]]]; (*This should be the list of market inputs for the first security (any will do) that has this curve input *)
             crvname = x2[[-2]]; (* This relies on the curve name being 2nd from end - not a reliable way to do it *)
             icrv = Flatten[Position[marketDataNames, crvname]];(* This is the index of the appropriate curve in marketData *)
             xcurve = Flatten[marketDataValues[[icrv]], 1];
             mktinputsup = xcurve[[6]];
             ix = Flatten[Position[xcurve[[6, 1]], rflist[[i]]]];(* Index of this market input in the list *)
             in = xcurve[[6, 3, ix]];
             inup = in + h;  mktinputsup[[3, ix]] = inup; 
             xcurveup = bootstrapcurve[settledate, xcurve, mktinputsup];
             xmarketDataup[[icrv]] = xcurveup;(* Now need to write the curvevars into the appropriate place in market data *)
             For[j = 1, j <= Length[xcurveup[[5]]], j++,
               ix = Flatten[Position[marketDataNames, xcurveup[[5, j]]]];
               xmarketDataup[[ix]] = xcurveup[[3, ix]];
               ];  (* End "for j" *)  ,
             _, Return["error in calcsimulatedPL"]
];     (* End "Switch" *)
];  (* End "For i" on RFs *)
           (* Now calculate the portfolio value for this bumped set of market data and calculate the P&L *)
           x2 = pvPort[seclist, holdings, settledate, xmarketDataup];
           pandl[[k + 1, 2 ;; countsec+1]] = x2 - baseval;                                        (* This will be the P&L  *)
            ]; (* End loop on draws *)    
              ]; (* end If on Abort *)
       x2 = pandl[[2;;ndraws+1]];   (* 1st col is zero so OK to include it in sum *)
       x2 = Total[x2,{2}];
       pandl[[2;;ndraws+1,1]]=x2;   (* Inserts total into 1st col *)
           pandl                             (* Output P&L *)
           ] (* end Module *)



pdf[dist_,x_] := Module[{normdist,sigma,alpha,beta,normsig,y},
If[Head[dist] =!= normalmixture,Return[PDF[dist,x]],
(* If a list, then assumed to be {"MixtureNormals",normdist, sigma, alpha,beta}. The sigma is the SD of the mixture, and the sigma of the underlying normals are sigma/Sqrt[1-alpha+alpah*beta^2] and beta*sigma... *)
normdist=dist[[1]];
sigma=dist[[2]];
alpha=dist[[3]];
beta=dist[[4]];
normsig=sigma/Sqrt[(1-alpha)+alpha*beta^2];
y = (1-alpha)*PDF[normdist[normsig],x] + alpha*PDF[normdist[beta*normsig],x];
Return[y]]
(* PDF[dist,x]*)]



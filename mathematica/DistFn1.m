Return[y]]
(* PDF[dist,x]*)]


(* ::Input::Initialization:: *)
quantile[dist_,p_] := Module[{normdist,sigma,x,xstart,y},
If[Head[dist] =!= normalmixture,Return[Quantile[dist,p]],
(* If a list, then assumed to be {"MixtureNormals",normdist, sigma, alpha,beta}. The sigma is the SD of the mixture, and the sigma of the underlying normals are sigma/Sqrt[1-alpha+alpah*beta^2] and beta*sigma... *)
If[(p<=0)||(1<=p),Return["Error"],
normdist=dist[[1]];
sigma=dist[[2]];
xstart = Quantile[normdist[sigma],p];
y = x /. FindRoot[cdf[dist,x]-p,{x,xstart}];
Return[y]]
]
